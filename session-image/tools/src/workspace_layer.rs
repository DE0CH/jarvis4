//! workspace-layer [WS] (the session entrypoint runs it on every boot when ~/workspace holds several repos): the
//! workspace-level project layer.
//!
//! With several repos, claude runs with cwd = ~/workspace, and Claude Code only discovers CLAUDE.md, .claude/skills,
//! .claude/commands, .claude/settings.json and hooks from the cwd and its ANCESTORS, never from subdirectories, and
//! `--add-dir` loads none of them. So it writes, at the workspace root:
//!
//!   CLAUDE.md                 imports every repo's CLAUDE.md (`@<repo>/CLAUDE.md`)
//!   .claude/<kind>/<name>     a link to `<repo>/.claude/<kind>/<name>` for skills, commands, agents and rules
//!                             (a clash is named `<repo>--<name>`)
//!   .claude/settings.json     every repo's .claude/settings.json merged: permission lists and hooks concatenated,
//!                             env, permission settings and other keys from the first repo that sets them
//!
//! Every path in the layer is relative to the workspace root (relative links, `$CLAUDE_PROJECT_DIR/<repo>` in hook
//! commands, `/<repo>/…` in file rules), because the layer is written on the machine at /home/claude/workspace and an
//! aviary session's Claude Code reads it inside its sandbox at /workspace (aviary_sandbox.rs): absolute paths written
//! here pointed at nothing there, the git guard hook could not start, and every Bash call was refused (2026-11-19).
//!
//! The workspace root is Jarvis's: the layer is rewritten whole on every boot and nothing hand-written lives there.

use serde_json::{Map, Value};
use std::fs;
use std::path::Path;

pub const TAG: &str = "[workspace-layer]";

const KINDS: [&str; 4] = ["skills", "commands", "agents", "rules"];
const FILE_TOOLS: [&str; 5] = ["Read", "Edit", "Write", "MultiEdit", "NotebookEdit"];

/// The repos in the order their settings win: SESSION_REPOS's order, then the other directories sorted.
pub fn repo_order(session_repos: &str, dirs: &[String]) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for url in session_repos.split(',') {
        let base = url
            .trim()
            .trim_end_matches('/')
            .rsplit('/')
            .next()
            .unwrap_or("");
        let name = base.strip_suffix(".git").unwrap_or(base);
        if !name.is_empty() && dirs.iter().any(|d| d == name) && !out.iter().any(|o| o == name) {
            out.push(name.to_string());
        }
    }
    let mut rest: Vec<&String> = dirs.iter().filter(|d| !out.contains(d)).collect();
    rest.sort();
    out.extend(rest.into_iter().cloned());
    out
}

/// The generated CLAUDE.md: `repos_with_md` are the repos (in order) that have one.
pub fn claude_md(repos: &[String], repos_with_md: &[String]) -> String {
    let mut s =
        String::from("# Multi-repo session (generated by workspace-layer — do not edit)\n\n");
    s.push_str("This session's working directory holds several repos side by side:\n");
    for r in repos {
        s.push_str(&format!("- `{r}/`\n"));
    }
    s.push_str(
        "\nEach repo's own instructions are imported below and apply to work inside that repo.\n\
         Run git commands inside the repo directories, not here. Skills, hooks and permission\n\
         rules from every repo are active (see `.claude/` here, which links to the repos' own).\n\n",
    );
    for r in repos_with_md {
        s.push_str(&format!("## {r}\n\n@{r}/CLAUDE.md\n\n"));
    }
    s
}

/// The links of one kind: (link name, relative target), from each repo's entries in order.
pub fn links(kind: &str, entries: &[(String, Vec<String>)]) -> Vec<(String, String)> {
    let mut out: Vec<(String, String)> = Vec::new();
    for (repo, names) in entries {
        for name in names {
            let link = if out.iter().any(|(l, _)| l == name) {
                format!("{repo}--{name}")
            } else {
                name.clone()
            };
            out.push((link, format!("../../{repo}/.claude/{kind}/{name}")));
        }
    }
    out
}

/// A repo's file-tool rule re-anchored at the workspace root: `Read(/x)` (the repo's root) and `Read(x)` (the cwd,
/// which was the repo) both become `Read(/<repo>/x)`; `//abs` and `~/…` stay.
pub fn scope_rule(rule: &str, repo: &str) -> String {
    let Some((tool, rest)) = rule.split_once('(') else {
        return rule.to_string();
    };
    let Some(pat) = rest.strip_suffix(')') else {
        return rule.to_string();
    };
    if !FILE_TOOLS.contains(&tool) || pat.starts_with("//") || pat.starts_with('~') {
        return rule.to_string();
    }
    let pat = pat.strip_prefix("./").unwrap_or(pat);
    format!("{tool}(/{repo}/{})", pat.trim_start_matches('/'))
}

/// `$CLAUDE_PROJECT_DIR` in a repo's commands meant the repo; Claude Code sets it to the workspace root here.
fn subst(v: &Value, repo: &str) -> Value {
    match v {
        // `${…}` first; the bare form then cannot match it again (a `{` follows its `$`)
        Value::String(s) => Value::String(
            s.replace(
                "${CLAUDE_PROJECT_DIR}",
                &format!("${{CLAUDE_PROJECT_DIR}}/{repo}"),
            )
            .replace(
                "$CLAUDE_PROJECT_DIR",
                &format!("$CLAUDE_PROJECT_DIR/{repo}"),
            ),
        ),
        Value::Array(a) => Value::Array(a.iter().map(|x| subst(x, repo)).collect()),
        Value::Object(o) => {
            Value::Object(o.iter().map(|(k, x)| (k.clone(), subst(x, repo))).collect())
        }
        other => other.clone(),
    }
}

fn push_unique(list: &mut Value, item: Value) {
    if let Value::Array(a) = list
        && !a.contains(&item)
    {
        a.push(item);
    }
}

/// Every repo's settings (in order) merged into the workspace's; the notes say what was dropped.
pub fn merge_settings(repos: &[(String, Value)]) -> (Value, Vec<String>) {
    let mut merged = Map::new();
    let mut notes = Vec::new();
    for (repo, s) in repos {
        let Value::Object(s) = s else {
            notes.push(format!("{repo}: settings.json is not an object; skipped"));
            continue;
        };
        for (k, v) in s {
            match k.as_str() {
                "permissions" => {
                    let mp = merged
                        .entry("permissions")
                        .or_insert_with(|| Value::Object(Map::new()));
                    let Value::Object(mp) = mp else { continue };
                    let Value::Object(v) = v else { continue };
                    for (pk, pv) in v {
                        match pk.as_str() {
                            "allow" | "deny" | "ask" => {
                                let list =
                                    mp.entry(pk.clone()).or_insert_with(|| Value::Array(vec![]));
                                for rule in pv.as_array().into_iter().flatten() {
                                    if let Some(r) = rule.as_str() {
                                        push_unique(list, Value::String(scope_rule(r, repo)));
                                    }
                                }
                            }
                            "additionalDirectories" => {
                                let list =
                                    mp.entry(pk.clone()).or_insert_with(|| Value::Array(vec![]));
                                for d in pv.as_array().into_iter().flatten() {
                                    if let Some(d) = d.as_str() {
                                        let d = if d.starts_with('/') || d.starts_with('~') {
                                            d.to_string()
                                        } else {
                                            format!("{repo}/{}", d.strip_prefix("./").unwrap_or(d))
                                        };
                                        push_unique(list, Value::String(d));
                                    }
                                }
                            }
                            _ => match mp.get(pk) {
                                Some(have) if have != pv => notes.push(format!(
                                    "{repo}: permissions.{pk} conflicts; keeping earlier"
                                )),
                                Some(_) => {}
                                None => {
                                    mp.insert(pk.clone(), pv.clone());
                                }
                            },
                        }
                    }
                }
                "hooks" => {
                    let mh = merged
                        .entry("hooks")
                        .or_insert_with(|| Value::Object(Map::new()));
                    let (Value::Object(mh), Value::Object(v)) = (mh, v) else {
                        continue;
                    };
                    for (ev, groups) in v {
                        let list = mh.entry(ev.clone()).or_insert_with(|| Value::Array(vec![]));
                        if let (Value::Array(list), Value::Array(groups)) = (list, groups) {
                            list.extend(groups.iter().map(|g| subst(g, repo)));
                        }
                    }
                }
                "env" => {
                    let me = merged
                        .entry("env")
                        .or_insert_with(|| Value::Object(Map::new()));
                    let (Value::Object(me), Value::Object(v)) = (me, v) else {
                        continue;
                    };
                    for (ek, ev) in v {
                        match me.get(ek) {
                            Some(have) if have != ev => {
                                notes.push(format!("{repo}: env.{ek} conflicts; keeping earlier"))
                            }
                            Some(_) => {}
                            None => {
                                me.insert(ek.clone(), ev.clone());
                            }
                        }
                    }
                }
                _ => {
                    let v = subst(v, repo);
                    match merged.get(k) {
                        Some(have) if *have != v => {
                            notes.push(format!("{repo}: {k} conflicts; keeping earlier"))
                        }
                        Some(_) => {}
                        None => {
                            merged.insert(k.clone(), v);
                        }
                    }
                }
            }
        }
    }
    (Value::Object(merged), notes)
}

fn say(msg: &str) {
    println!("{TAG} {msg}");
}

fn sorted_names(dir: &Path, only_dirs: bool) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter(|e| !only_dirs || e.path().is_dir())
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| !only_dirs || !n.starts_with('.'))
        .collect();
    names.sort();
    names
}

/// Writes the layer for the workspace `ws` (nothing with fewer than two repos).
pub fn write(ws: &Path) -> Result<(), String> {
    let dirs = sorted_names(ws, true);
    let repos = repo_order(&std::env::var("SESSION_REPOS").unwrap_or_default(), &dirs);
    if repos.len() < 2 {
        say(&format!(
            "{} repo(s) under {}; nothing to generate",
            repos.len(),
            ws.display()
        ));
        return Ok(());
    }
    say(&format!("repos: {}", repos.join(" ")));
    let claude = ws.join(".claude");
    if claude.exists() {
        fs::remove_dir_all(&claude).map_err(|e| format!("removing {}: {e}", claude.display()))?;
    }
    fs::create_dir_all(&claude).map_err(|e| format!("making {}: {e}", claude.display()))?;

    let with_md: Vec<String> = repos
        .iter()
        .filter(|r| ws.join(r).join("CLAUDE.md").is_file())
        .cloned()
        .collect();
    fs::write(ws.join("CLAUDE.md"), claude_md(&repos, &with_md))
        .map_err(|e| format!("writing CLAUDE.md: {e}"))?;

    for kind in KINDS {
        let entries: Vec<(String, Vec<String>)> = repos
            .iter()
            .map(|r| {
                (
                    r.clone(),
                    sorted_names(&ws.join(r).join(".claude").join(kind), false),
                )
            })
            .collect();
        let ls = links(kind, &entries);
        if ls.is_empty() {
            continue;
        }
        let dir = claude.join(kind);
        fs::create_dir_all(&dir).map_err(|e| format!("making {}: {e}", dir.display()))?;
        for (name, target) in &ls {
            std::os::unix::fs::symlink(target, dir.join(name))
                .map_err(|e| format!("linking {kind}/{name}: {e}"))?;
        }
        say(&format!("{kind}: {} linked", ls.len()));
    }

    let mut settings = Vec::new();
    let mut notes = Vec::new();
    for r in &repos {
        let p = ws.join(r).join(".claude").join("settings.json");
        let Ok(text) = fs::read_to_string(&p) else {
            continue;
        };
        match serde_json::from_str::<Value>(&text) {
            Ok(v) => settings.push((r.clone(), v)),
            Err(e) => notes.push(format!("{r}: settings.json unreadable ({e}); skipped")),
        }
    }
    let (merged, more) = merge_settings(&settings);
    notes.extend(more);
    let text = serde_json::to_string_pretty(&merged).map_err(|e| e.to_string())?;
    fs::write(claude.join("settings.json"), text + "\n")
        .map_err(|e| format!("writing settings.json: {e}"))?;
    let count = |k: &str| merged["permissions"][k].as_array().map_or(0, |a| a.len());
    let groups: usize = merged["hooks"].as_object().map_or(0, |h| {
        h.values()
            .filter_map(|g| g.as_array())
            .map(|g| g.len())
            .sum()
    });
    say(&format!(
        "settings.json: {} allow, {} deny, {groups} hook group(s)",
        count("allow"),
        count("deny")
    ));
    for n in notes {
        say(&format!("note: {n}"));
    }
    say("done");
    Ok(())
}

pub fn run(args: &[String]) -> Result<std::process::ExitCode, String> {
    let ws = match args.first() {
        Some(w) => w.clone(),
        None => format!(
            "{}/workspace",
            std::env::var("HOME").map_err(|_| "no HOME")?
        ),
    };
    write(Path::new(&ws))?;
    Ok(std::process::ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn session_repos_order_first_then_the_rest_sorted() {
        let dirs = vec![
            "src".to_string(),
            "claude-env".to_string(),
            "aviary".to_string(),
        ];
        assert_eq!(
            repo_order(
                " https://github.com/DE0CH/claude-env.git, https://github.com/DE0CH/gone",
                &dirs
            ),
            vec!["claude-env", "aviary", "src"]
        );
    }

    #[test]
    fn links_are_relative_and_a_clash_is_prefixed() {
        let ls = links(
            "skills",
            &[
                ("a".into(), vec!["x".into()]),
                ("b".into(), vec!["x".into(), "y".into()]),
            ],
        );
        assert_eq!(
            ls,
            vec![
                ("x".into(), "../../a/.claude/skills/x".into()),
                ("b--x".into(), "../../b/.claude/skills/x".into()),
                ("y".into(), "../../b/.claude/skills/y".into()),
            ]
        );
    }

    #[test]
    fn file_rules_are_anchored_at_the_workspace_root() {
        assert_eq!(scope_rule("Read(/docs/**)", "r"), "Read(/r/docs/**)");
        assert_eq!(scope_rule("Edit(src/*.rs)", "r"), "Edit(/r/src/*.rs)");
        assert_eq!(scope_rule("Edit(./src/*.rs)", "r"), "Edit(/r/src/*.rs)");
        assert_eq!(scope_rule("Read(//etc/hosts)", "r"), "Read(//etc/hosts)");
        assert_eq!(scope_rule("Read(~/.zshrc)", "r"), "Read(~/.zshrc)");
        assert_eq!(scope_rule("Bash(git status)", "r"), "Bash(git status)");
    }

    /// The layer is read at another path than it is written at (an aviary sandbox's /workspace): nothing in it may
    /// name the machine's workspace.
    #[test]
    fn hook_commands_stay_relative_to_the_project_dir() {
        let hook = json!({"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command",
            "command": "python3 \"$CLAUDE_PROJECT_DIR/.claude/hooks/git_guard.py\" ${CLAUDE_PROJECT_DIR}/x"}]}]});
        let (m, notes) = merge_settings(&[
            (
                "claude-env".into(),
                json!({"hooks": hook, "permissions": {"allow": ["Read(a)"], "defaultMode": "auto"}}),
            ),
            (
                "src".into(),
                json!({"hooks": {"PreToolUse": [{"matcher": "Edit"}]},
                "permissions": {"allow": ["Read(a)"], "defaultMode": "plan"}, "env": {"A": "1"}}),
            ),
        ]);
        assert_eq!(
            m["hooks"]["PreToolUse"][0]["hooks"][0]["command"],
            "python3 \"$CLAUDE_PROJECT_DIR/claude-env/.claude/hooks/git_guard.py\" ${CLAUDE_PROJECT_DIR}/claude-env/x"
        );
        assert_eq!(m["hooks"]["PreToolUse"].as_array().unwrap().len(), 2);
        assert_eq!(
            m["permissions"]["allow"],
            json!(["Read(/claude-env/a)", "Read(/src/a)"])
        );
        assert_eq!(m["permissions"]["defaultMode"], "auto");
        assert_eq!(m["env"]["A"], "1");
        assert_eq!(
            notes,
            vec!["src: permissions.defaultMode conflicts; keeping earlier"]
        );
    }

    #[test]
    fn writes_a_layer_that_works_from_another_mount_point() {
        let ws = std::env::temp_dir().join(format!("wslayer-{}", std::process::id()));
        let _ = fs::remove_dir_all(&ws);
        for r in ["a", "b"] {
            fs::create_dir_all(ws.join(r).join(".claude/skills/s")).unwrap();
            fs::write(ws.join(r).join("CLAUDE.md"), r).unwrap();
        }
        fs::write(
            ws.join("a/.claude/settings.json"),
            r#"{"hooks":{"PreToolUse":[{"hooks":[{"type":"command","command":"$CLAUDE_PROJECT_DIR/h"}]}]}}"#,
        )
        .unwrap();
        write(&ws).unwrap();
        // the same tree seen at another path, as the sandbox sees it
        let moved = std::env::temp_dir().join(format!("wslayer-moved-{}", std::process::id()));
        let _ = fs::remove_dir_all(&moved);
        fs::rename(&ws, &moved).unwrap();
        assert!(
            moved.join(".claude/skills/s/.").is_dir(),
            "a skill link does not resolve after the move"
        );
        assert!(moved.join(".claude/skills/b--s/.").is_dir());
        let settings = fs::read_to_string(moved.join(".claude/settings.json")).unwrap();
        assert!(
            !settings.contains(&ws.display().to_string()),
            "settings name the old path: {settings}"
        );
        assert!(settings.contains("$CLAUDE_PROJECT_DIR/a/h"));
        let md = fs::read_to_string(moved.join("CLAUDE.md")).unwrap();
        assert!(md.contains("@a/CLAUDE.md") && md.contains("@b/CLAUDE.md"));
        fs::remove_dir_all(&moved).unwrap();
    }
}
