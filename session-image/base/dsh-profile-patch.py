#!/usr/bin/env python3
"""The DeepSeek Harness (dsh) web profile patch for a Jarvis 4 session (harness-dsh.sh runs it at every boot).

usage: dsh-profile-patch.py DUMP.yml MODELS_JSON DEFAULT_MODEL SKILL_DIR... > cordis.patch.yml

DUMP.yml is `dsh --profile web --dump-config` of the installed dsh with the profile patch emptied, so the result
always matches the installed version. dsh offers no per-row patch inside an agent preset: a profile patch keyed by
a preset row replaces that row's whole config. So every preset is copied and, inside it:
  agent-instructions  expandImports on (the workspace CLAUDE.md is only `@<repo>/CLAUDE.md` lines and claude-env's
                      imports lessons.md) and a budget that holds those chains
  skill-filesystem    customSkillDirs = the Claude Code skill roots (the workspace's .claude/skills, ~/.claude/skills)
Plus the model route `openrouter-deepseek`: OpenRouter's OpenAI-compatible API with routing pinned to the DeepSeek provider
(DeepSeek's own endpoints: only the dated slugs have one), MODELS_JSON = [{id, name}], and DEFAULT_MODEL (an OpenRouter
slug from that list) as the default for new conversations.
`!!js` expressions in the dump stay as written.
"""
import json
import sys

import yaml

INSTRUCTION_BUDGET = 262144
# the pi-ai route id; its models are OpenRouter slugs (Jarvis 4's SESSION_MODEL is dsh/<slug>)
PROVIDER = "openrouter-deepseek"


class Js(str):
    pass


def js_constructor(loader, node):
    return Js(loader.construct_scalar(node))


def js_representer(dumper, value):
    return dumper.represent_scalar("tag:yaml.org,2002:js", str(value))


yaml.SafeLoader.add_constructor("tag:yaml.org,2002:js", js_constructor)
yaml.SafeDumper.add_representer(Js, js_representer)


def patch_plugins(plugins, skill_dirs):
    for row in plugins:
        if not isinstance(row, dict):
            continue
        name = row.get("name")
        if name == "@deepseek-ai/dsh-agent-instructions":
            config = dict(row.get("config") or {})
            config["maxBytes"] = max(int(config.get("maxBytes") or 0), INSTRUCTION_BUDGET)
            config["expandImports"] = True
            row["config"] = config
        elif name == "@deepseek-ai/dsh-skill-filesystem":
            config = dict(row.get("config") or {})
            config["customSkillDirs"] = list(dict.fromkeys([*(config.get("customSkillDirs") or []), *skill_dirs]))
            row["config"] = config
        if row.get("group") and isinstance(row.get("config"), list):
            patch_plugins(row["config"], skill_dirs)


def main():
    dump_path, models_json, default_model, *skill_dirs = sys.argv[1:]
    entries = yaml.safe_load(open(dump_path)) or []
    patches = []
    for entry in entries:
        if isinstance(entry, dict) and entry.get("name") == "@deepseek-ai/dsh-agent-preset" and entry.get("id"):
            config = entry.get("config") or {}
            patch_plugins(config.get("plugins") or [], skill_dirs)
            patches.append({"id": entry["id"], "config": config})
    models = json.loads(models_json)
    patches.append({
        "id": "llm-pi-ai",
        "config": {
            "providers": {
                PROVIDER: {
                    "displayName": "OpenRouter · DeepSeek",
                    "api": "openai-completions",
                    "baseURL": "https://openrouter.ai/api/v1",
                    "apiKeyEnv": "OPENROUTER_API_KEY",
                    "reasoning": "high",
                    "compat": {
                        "thinkingFormat": "openrouter",
                        "openRouterRouting": {"only": ["deepseek"], "allow_fallbacks": False},
                    },
                    "models": [{
                        "id": m["id"],
                        **({"name": m["name"]} if m.get("name") else {}),
                        "contextWindow": 1048576,
                        "maxTokens": 65536,
                        "reasoningEfforts": {"off": None, "low": "low", "high": "high"},
                    } for m in models],
                },
            },
        },
    })
    patches.append({"id": "agent-default-model", "config": {"provider": PROVIDER, "model": default_model}})
    sys.stdout.write("# Generated by dsh-profile-patch.py at boot (harness-dsh.sh); edits are overwritten.\n")
    yaml.safe_dump(patches, sys.stdout, sort_keys=False, allow_unicode=True, width=1000)


if __name__ == "__main__":
    main()
